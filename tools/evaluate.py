# A language is a PASS only if its aggregate round-trip WER clears this ceiling AND
# the English self-check passed. The verdict is derived from the number, never typed.
WER_PASS_CEILING = 0.15
CER_PASS_CEILING = 0.10
SELF_CHECK_CEILING = 0.05


def _manifest(name: str):
    return load_manifest(Path(models_dir()) / "manifests" / f"{name}.json")


def _free_ram_gb() -> float | None:
    from nativevoice.hardware.detect import detect

    available_mb = detect().ram_available_mb
    return None if available_mb is None else round(available_mb / 1024, 3)


def _run_language(tts_manifest, stt_manifest, code: str, *, sid: int, keep_wav: bool):
    """Synthesise then transcribe one language's sentences. Returns a result dict."""
    sentences = CORPUS[code]
    entry = {
        "language": code,
        "tts_engine": tts_manifest.engine,
        "stt_engine": stt_manifest.engine,
        "pairs": len(sentences),
        "utterances": [],
    }
    engine = SherpaKokoroEngine(tts_manifest, resolve_asset_dir(tts_manifest))
    # Refusal probe: the engine must not silently produce audio for a language it
    # has no front-end for. hi/bn raise here rather than emitting romanised gibberish.
    try:
        front_end = engine._lang_for(LanguageTag(code))
        engine.warm(front_end)
    except Exception as exc:  # unsupported TTS language: record it and stop
        entry["tts_status"] = "refused"
        entry["tts_error"] = f"{type(exc).__name__}: {exc}"
        entry["verdict"] = "UNSUPPORTED"
        entry["conclusion"] = (
            "the Kokoro asset has no front-end for this language; it refuses rather than "
            "emit romanised gibberish, so no round-trip number exists"
        )
        entry["tts_status_enum"] = CapabilityStatus.UNSUPPORTED.value
        return entry

    wav_dir = Path("artifacts/evaluation/audio")
    produced = []
    for index, text in enumerate(sentences):
        synth_start = time.monotonic()
        outcome = engine.synthesize(SynthesisRequest(text=text, language=LanguageTag(code)))
        synth_ms = (time.monotonic() - synth_start) * 1000.0
        first_audio_ms = outcome.timings.get("first_audio_ms") or outcome.timings.get("first_result_ms")
        measurement = measure_synthesis(
            outcome.audio,
            wall_time_ms=synth_ms,
            first_audio_ms=first_audio_ms,
            maximum_duration_s=outcome.audio.duration_s,
            engine=engine.engine_id,
            model_id=engine.model_id,
            language=code,
        )
        produced.append((index, text, outcome.audio, measurement))
        if keep_wav and index < 1 and code in ("en", "zh"):
            wav_dir.mkdir(parents=True, exist_ok=True)
            wav_path = wav_dir / f"roundtrip_{code}_{index}.wav"
            write_wav(str(wav_path), outcome.audio)
    engine.close()

    stt = FasterWhisperEngine(stt_manifest, device="cpu", cpu_threads=2, vad_filter=True)
    stt.warm()
    auto_wers, forced_wers = [], []
    for index, text, audio, measurement in produced:
        audio16 = resample(audio, 16000)
        transcribe_start = time.monotonic()
        auto = stt.transcribe(TranscriptionRequest(audio=audio16, allow_auto_detection=True))
        forced = stt.transcribe(
            TranscriptionRequest(audio=audio16, language=LanguageTag(code), allow_auto_detection=False)
        )
        stt_ms = time.monotonic() - transcribe_start
        auto_score = score(text, auto.text, code)
        forced_score = score(text, forced.text, code)
        auto_wers.append(auto_score)
        forced_wers.append(forced_score)
        entry["utterances"].append(
            {
                "index": index,
                "reference": text,
                "hypothesis_auto": auto.text,
                "hypothesis_forced": forced.text,
                "detected_language": auto.language.bcp47 if auto.language else None,
                "auto_wer": _num(auto_score.wer),
                "auto_cer": _num(auto_score.cer),
                "forced_wer": _num(forced_score.wer),
                "forced_cer": _num(forced_score.cer),
                "tts_real_time_factor": measurement.real_time_factor,
                "tts_first_audio_ms": measurement.first_audio_ms,
                "tts_audio_duration_s": round(measurement.audio_duration_s, 4),
                "stt_real_time_factor": round(stt_ms / max(1e-6, audio.duration_s), 4),
                "audio_rms": round(rms(audio.samples), 5),
            }
        )
    stt.close()

    entry["tts_status"] = "synthesised"
    name, value, ceiling = _primary_metric(entry)
    entry["primary_metric"] = name
    entry["primary_value"] = value
    entry["primary_ceiling"] = ceiling
    entry["auto_wer"] = _micro(auto_wers)
    entry["auto_cer"] = _micro(auto_wers, char=True)
    entry["forced_wer"] = _micro(forced_wers)
    entry["forced_cer"] = _micro(forced_wers, char=True)
    entry["mean_tts_rtf"] = _mean([u["tts_real_time_factor"] for u in entry["utterances"]])
    entry["mean_tts_first_audio_ms"] = _mean([u["tts_first_audio_ms"] for u in entry["utterances"]])
    entry["mean_stt_rtf"] = _mean([u["stt_real_time_factor"] for u in entry["utterances"]])
    # The honest verdict: use the forced run (language was known) as the headline.
    wer = entry["forced_wer"]
    entry["tts_status_enum"] = CapabilityStatus.MEASURED.value if wer is not None else CapabilityStatus.DECLARED.value
    return entry


def _num(value):
    return None if value == float("inf") else round(value, 6)


def _micro(scores, char=False):
    """Micro-average error rate: total edits over total reference tokens."""
    distance = sum(s.word.alignment.distance if not char else s.character.alignment.distance for s in scores)
    reference = sum(s.reference_tokens if not char else s.character.alignment.reference_length for s in scores)
    if reference == 0:
        return None if distance else 0.0
    return round(distance / reference, 6)


def _mean(values):
    present = [v for v in values if v is not None]
    return None if not present else round(sum(present) / len(present), 4)


def _primary_metric(entry):
    """The metric that is actually valid for this writing system.

    Word error rate on an unsegmented script counts the whole sentence as one token,
    so a single wrong character reports WER 1.000 and every Chinese result looks like
    total failure. Character error rate is the honest measure there, and the language
    registry's `space_delimited` flag is what decides which one is primary.
    """
    from nativevoice.language import LanguageRegistry

    profile = None
    try:
        profile = LanguageRegistry().lookup(entry["language"])
    except Exception:
        profile = None
    if profile is not None and not profile.space_delimited:
        return "cer", entry.get("forced_cer"), CER_PASS_CEILING
    return "wer", entry.get("forced_wer"), WER_PASS_CEILING


def _verdict_for(entry, self_check_ok):
    if entry.get("tts_status") == "refused":
        return "UNSUPPORTED"
    _name, value, _ceiling = _primary_metric(entry)
    if value is None:
        return "NOT_RUN"
    if not self_check_ok:
        return "SELF-CHECK FAILED (numbers untrustworthy)"
    return "PASS" if value <= _ceiling else "FAIL"


def _capabilities(entries, artifact_path):
    """Build ledger Capabilities: MEASURED only where a round-trip number exists."""
    today = date.today().isoformat()
    caps = []
    for entry in entries:
        code = entry["language"]
        verdict = entry["verdict"]
        if verdict == "PASS":
            caps.append(
                Capability(
                    task=Task.TTS,
                    status=CapabilityStatus.MEASURED,
                    language=code,
                    engine="sherpa-onnx-kokoro",
                    metric_name=f"roundtrip_{_primary_metric(entry)[0]}",
                    metric_value=entry["forced_wer"],
                    measured_on=today,
                    model_id=TTS_MODEL_ID,
                    limitations=(PAIR_NOTE,),
                    evidence=artifact_path,
                )
            )
            caps.append(
                Capability(
                    task=Task.STT,
                    status=CapabilityStatus.MEASURED,
                    language=code,
                    engine="faster-whisper",
                    metric_name=f"roundtrip_{_primary_metric(entry)[0]}",
                    metric_value=entry["forced_wer"],
                    measured_on=today,
                    model_id=STT_MODEL_ID,
                    limitations=(PAIR_NOTE, "measured against machine-generated speech, not human speech"),
                    evidence=artifact_path,
                )
            )
        elif verdict == "UNSUPPORTED":
            caps.append(
                Capability(
                    task=Task.TTS,
                    status=CapabilityStatus.UNSUPPORTED,
                    language=code,
                    engine="sherpa-onnx-kokoro",
                    model_id=TTS_MODEL_ID,
                    limitations=(entry.get("conclusion", "asset has no front-end for this language"),),
                    evidence=artifact_path,
                )
            )
            caps.append(
                Capability(
                    task=Task.STT,
                    status=CapabilityStatus.DECLARED,
                    language=code,
                    engine="faster-whisper",
                    model_id=STT_MODEL_ID,
                    limitations=(
                        "vendor model-card language claim; could not be measured because no "
                        "licensed human-speech (or synthesable) audio for this language exists here",
                    ),
                    evidence=artifact_path,
                )
            )
        elif verdict == "FAIL":
            # Measured, and the measurement failed the bar. That is still a
            # measurement - so it is recorded (never dropped) as MEASURED_FAILED,
            # which routes like UNSUPPORTED but keeps the number that tells an
            # engineer whether the gap is a missing asset or a bad one.
            caps.append(
                Capability(
                    task=Task.TTS,
                    status=CapabilityStatus.MEASURED_FAILED,
                    language=code,
                    engine="sherpa-onnx-kokoro",
                    model_id=TTS_MODEL_ID,
                    metric_name=f"roundtrip_{_primary_metric(entry)[0]}",
                    metric_value=_primary_metric(entry)[1],
                    measured_on=date.today().isoformat(),
                    limitations=(
                        f"front-end exists but the primary round-trip metric "
                        f"{_primary_metric(entry)[0].upper()} {_primary_metric(entry)[1]} fails the "
                        f"{_primary_metric(entry)[2]} bar; a front-end is present yet the audio is not "
                        "intelligible to the listening engine (see the reference vs hypothesis detail). "
                        "For Chinese the numbers also carry a simplified-vs-traditional mismatch, "
                        "because no approved converter is available to normalise either side",
                        PAIR_NOTE,
                    ),
                    evidence=artifact_path,
                )
            )
            caps.append(
                Capability(
                    task=Task.STT,
                    status=CapabilityStatus.DECLARED,
                    language=code,
                    engine="faster-whisper",
                    model_id=STT_MODEL_ID,
                    limitations=(
                        "recognition on this language could not be isolated from the synthesis "
                        "failure above, so no clean STT measurement exists; vendor claim only",
                    ),
                    evidence=artifact_path,
                )
            )
    return caps


def _matrix_markdown(capabilities, tasks):
    matrix = build_matrix(
        [(cap.language, cap) for cap in capabilities], tasks=tasks
    )
    langs = sorted({cap.language for cap in capabilities})
    lines = [
        "# Capability matrix",
        "",
        f"Generated {date.today().isoformat()}. Symbols: M=measured here, d=declared (vendor, unverified), P=partial, !=measured and failed the bar, "
        "P=partial, x=unsupported, -=awaiting model. Round-trip cells measure the TTS+STT pair on "
        "machine-generated, licence-clean audio (see each capability's evidence path).",
        "",
        "| language | " + " | ".join(t.value for t in tasks) + " |",
        "| " + " | ".join("---" for _ in range(len(tasks) + 1)) + " |",
    ]
    for code in langs:
        row = [code]
        for task in tasks:
            cell = matrix.cell(code, task.value)
            if cell is None:
                row.append("-")
            elif cell.metric_value is not None:
                row.append(f"{cell.symbol} ({cell.metric_value:.3f})")
            else:
                row.append(cell.symbol)
        lines.append("| " + " | ".join(row) + " |")
    return "\n".join(lines) + "\n"


def _profile_marking(peak_mb):
    """Attach observed peak RAM to a profile copy; name what stays unmeasured."""
    marked = {}
    unmeasured = ["max_threads", "max_audio_buffer_frames", "concurrency", "allowed_quantizations"]
    if peak_mb is not None:
        ceiling = int(peak_mb + 256)
        evidence = f"observed process peak RSS {peak_mb:.0f} MiB during round-trip eval"
        policy = hw.mark_measured(
            hw.get_profile("balanced"), evidence=evidence, max_resident_mib=ceiling
        )
        marked["balanced"] = {
            "name": policy.name,
            "measured": policy.measured,
            "provisional": policy.provisional,
            "max_resident_mib": policy.max_resident_mib,
            "validation_evidence": policy.validation_evidence,
            "still_provisional_fields": unmeasured,
        }
    return {
        "marked_profiles": marked,
        "observed_peak_rss_mib": peak_mb,
        "thresholds_still_unmeasured": unmeasured,
        "note": (
            "mark_measured flips a profile to measured=True but only max_resident_mib was "
            "backed by an observation here; the listed thresholds remain provisional seeds and "
            "must not be treated as validated."
        ),
    }


def run(languages, keep_wav=True):
    started = time.monotonic()
    tts_manifest = _manifest(TTS_MODEL_ID)
    stt_manifest = _manifest(STT_MODEL_ID)
    free_ram = _free_ram_gb()
    stamp = date.today().isoformat()
    artifact_path = f"artifacts/evaluation/roundtrip-{stamp}.json"
    artifact_root = Path(artifact_path).parent
    artifact_root.mkdir(parents=True, exist_ok=True)

    def _work():
        return [
            _run_language(tts_manifest, stt_manifest, code, sid=0, keep_wav=keep_wav)
            for code in languages
        ]

    sampler = Sampler(interval_s=0.1)
    entries, resource_run = sampler.run(_work)

    en = next((e for e in entries if e["language"] == "en"), None)
    self_check_ok = bool(en) and en.get("forced_wer") is not None and en["forced_wer"] <= SELF_CHECK_CEILING
    for entry in entries:
        entry["verdict"] = _verdict_for(entry, self_check_ok)

    capabilities = _capabilities(entries, artifact_path)
    ledger = CapabilityLedger()
    for cap in capabilities:
        ledger.record(cap)

    peak_mb = None if resource_run.peak_bytes is None else round(resource_run.peak_bytes / (1024 * 1024), 1)
    final_read = read_memory()

    report = {
        "title": "ULTRON Native Voice - round-trip intelligibility evaluation",
        "generated_on": stamp,
        "provenance": PAIR_NOTE,
        "self_check": {
            "language": "en",
            "forced_wer": None if en is None else en.get("forced_wer"),
            "threshold": SELF_CHECK_CEILING,
            "passed": self_check_ok,
            "meaning": "English round-trip is the harness self-check; if it fails, the chain is broken.",
        },
        "engines": {
            "tts": {"model_id": TTS_MODEL_ID, "engine": tts_manifest.engine, "review": tts_manifest.review.value},
            "stt": {"model_id": STT_MODEL_ID, "engine": stt_manifest.engine, "review": stt_manifest.review.value},
        },
        "environment": {
            "free_ram_gb_at_start": free_ram,
            "elapsed_s": round(time.monotonic() - started, 2),
        },
        "resources": {
            "peak_rss_mb_observed": peak_mb,
            "measured": resource_run.measured,
            "final_memory": final_read.as_dict(),
            "wall_s": round(resource_run.wall_s, 2),
        },
        "results": entries,
        "verdicts": {e["language"]: e["verdict"] for e in entries},
        "hardware_profiles": _profile_marking(peak_mb),
        "capability_ledger_report": {
            "tts": ledger.report(Task.TTS),
            "stt": ledger.report(Task.STT),
        },
    }

    Path(artifact_path).write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding="utf-8")
    Path("artifacts/evaluation/capability-matrix.md").write_text(
        _matrix_markdown(capabilities, (Task.TTS, Task.STT)), encoding="utf-8"
    )
    Path("artifacts/evaluation/roundtrip-" + stamp + ".md").write_text(_markdown(report), encoding="utf-8")
    return report


def _markdown(report):
    lines = [
        f"# {report['title']}",
        "",
        f"Generated {report['generated_on']}. {report['provenance']}",
        "",
        f"Self-check (en): WER={report['self_check']['forced_wer']} "
        f"(threshold {report['self_check']['threshold']}) -> "
        f"{'PASS' if report['self_check']['passed'] else 'FAIL'}",
        "",
        "Free RAM at start: {} GB. Peak RSS observed: {} MiB.".format(
            report["environment"]["free_ram_gb_at_start"], report["resources"]["peak_rss_mb_observed"]
        ),
        "",
        "| language | verdict | forced WER | forced CER | TTS RTF | TTS first-audio ms | STT RTF |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for entry in report["results"]:
        lines.append(
            "| {lang} | {verdict} | {fw} | {fc} | {rtf} | {ttfa} | {sttf} |".format(
                lang=entry["language"],
                verdict=entry["verdict"],
                fw=entry.get("forced_wer"),
                fc=entry.get("forced_cer"),
                rtf=entry.get("mean_tts_rtf"),
                ttfa=entry.get("mean_tts_first_audio_ms"),
                sttf=entry.get("mean_stt_rtf"),
            )
        )
    lines += [
        "",
        "## Per-utterance detail",
        "",
    ]
    for entry in report["results"]:
        lines.append(f"### {entry['language']} - {entry['verdict']}")
        if entry.get("conclusion"):
            lines.append(f"_{entry['conclusion']}_")
        for u in entry.get("utterances", []):
            lines.append(f"- ref: {u['reference']}")
            lines.append(f"  - forced hyp: {u.get('hypothesis_forced','')} (WER {u.get('forced_wer')}, CER {u.get('forced_cer')})")
        lines.append("")
    lines += [
        "## Hardware profiles",
        "",
        "Marked measured only for observed peak RSS; still unmeasured thresholds: "
        + ", ".join(report["hardware_profiles"]["thresholds_still_unmeasured"]),
        "",
        report["hardware_profiles"]["note"],
    ]
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--languages", nargs="+", default=["en", "hi", "bn", "zh"], choices=sorted(CORPUS))
    parser.add_argument("--no-wav", action="store_true", help="skip writing listenable WAV samples")
    args = parser.parse_args(argv)
    ordered = [c for c in ("en", "hi", "bn", "zh") if c in args.languages]
    report = run(ordered, keep_wav=not args.no_wav)
    print(json.dumps(report["verdicts"], indent=2))
    print(f"self-check en WER: {report['self_check']['forced_wer']}")
    print(f"peak RSS: {report['resources']['peak_rss_mb_observed']} MiB")
    print("wrote artifacts/evaluation/roundtrip-*.json/.md and capability-matrix.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
