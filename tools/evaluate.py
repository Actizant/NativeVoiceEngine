"""Round-trip intelligibility evaluation: our TTS speaks, our STT listens, we measure.

WHY THIS PATH EXISTS AND WHAT IT IS NOT. There is no licensed human-speech corpus on
this machine, and ``eval.samples`` correctly refuses synthetic fixtures in a quality
path. Synthetic speech generated by *our own approved TTS asset* is licence-clean,
and transcribing it with a *second approved engine* is a legitimate intelligibility
measurement - but it scores the TTS+STT **pair**, not human speech. Every line this
tool emits (JSON, markdown, and the capability records) states that provenance, and
the English run is used first as a self-check: if English round-trip WER is not near
zero, the measurement chain is broken, not the voices.

Nothing here runs on import. Run it explicitly:

    python tools/evaluate.py                      # real inference, writes artifacts
    python tools/evaluate.py --languages en zh    # restrict which languages to attempt

Artifacts land under ``artifacts/evaluation/``: ``roundtrip-<date>.json``, a human
``.md`` table, a regenerated ``capability-matrix.md``, up to four WAV samples, and the
hardware-profile markings for the numbers actually observed.
"""

